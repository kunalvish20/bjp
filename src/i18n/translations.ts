export function translateText(text: string) {
  const normalized = text.replace(/\s+/g, ' ').trim()
  if (!normalized) return undefined

  const exact = exactTranslations[normalized]
  if (exact) return exact

  const readTimeMatch = normalized.match(/^(\d+)\s+min read$/i)
  if (readTimeMatch) return `${readTimeMatch[1]} मिनट पढ़ें`

  const continueMatch = normalized.match(/^Continue with ₹(.+)$/)
  if (continueMatch) return `₹${continueMatch[1]} के साथ जारी रखें`

  if (normalized === 'Preparing secure checkout...') return 'सुरक्षित चेकआउट तैयार हो रहा है...'

  const monthDateMatch = normalized.match(/^([A-Za-z]+)\s+(\d{1,2}),\s+(\d{4})(?:\s+·\s+(.+))?$/)
  if (monthDateMatch && monthTranslations[monthDateMatch[1]]) {
    const date = `${monthDateMatch[2]} ${monthTranslations[monthDateMatch[1]]} ${monthDateMatch[3]}`
    return monthDateMatch[4] ? `${date} · ${monthDateMatch[4]}` : date
  }

  const dayMonthMatch = normalized.match(/^(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})$/)
  if (dayMonthMatch && monthTranslations[dayMonthMatch[2]]) {
    return `${dayMonthMatch[1]} ${monthTranslations[dayMonthMatch[2]]} ${dayMonthMatch[3]}`
  }

  return undefined
}
